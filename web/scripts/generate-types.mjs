// Writes lib/dataset/types.generated.ts from pipeline/ousd/schemas. A test fails if it drifts, so
// run this after any schema change: node scripts/generate-types.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const WEB_DIR = dirname(dirname(fileURLToPath(import.meta.url)));
const OUTPUT = join(WEB_DIR, "lib/dataset/types.generated.ts");
const SCHEMAS = [
  ["manifest", "ManifestFile"],
  ["summary", "SummaryFile"],
  ["journey", "JourneyFile"],
  ["activity", "ActivityFile"],
  ["chain_roles", "ChainRolesFile"],
  ["reconciliation", "ReconciliationFile"],
  ["labels", "LabelsFile"],
];

// json-schema-to-typescript reads neither `prefixItems` nor the release rules in `allOf`. Each
// position's name is a const, so the checks become a union, and Ajv still enforces the order.
function forTypes(schema) {
  if (Array.isArray(schema)) return schema.map(forTypes);
  if (schema === null || typeof schema !== "object") return schema;
  const out = {};
  for (const [key, value] of Object.entries(schema)) {
    if (key === "allOf" || key === "propertyNames") continue;
    if (key === "prefixItems") out.items = { anyOf: forTypes(value) };
    else if (!(key === "items" && value === false)) out[key] = forTypes(value);
  }
  return out;
}

export async function generateTypes(schemaDir) {
  const parts = [
    "// Generated by scripts/generate-types.mjs from pipeline/ousd/schemas. Don't edit.",
  ];
  for (const [name, typeName] of SCHEMAS) {
    const schema = JSON.parse(readFileSync(join(schemaDir, `${name}.schema.json`), "utf8"));
    const prepared = forTypes(schema);
    // The title would otherwise name the type.
    delete prepared.title;
    const code = await compile(prepared, typeName, {
      bannerComment: "",
      additionalProperties: false,
      ignoreMinAndMaxItems: true,
      style: { printWidth: 100 },
    });
    // The generator's own note on pattern properties names an undefined parent, so drop it.
    parts.push(
      code.replace(/\n\s*\/\*\*\n(\s*\*[^\n]*\n)*?\s*\*\/(?=\n\s*\[k: string\])/g, "").trim(),
    );
  }
  return `${parts.join("\n\n")}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, await generateTypes(join(WEB_DIR, "../pipeline/ousd/schemas")));
  console.log("lib/dataset/types.generated.ts");
}
